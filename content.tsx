export function getArticlePath(sectionId: string, articleSlug: string) {
  return `/docs/${sectionId}/${articleSlug}`
}

export const allArticles = docsSections.flatMap((section) =>
  section.links.map((article) => ({
    ...article,
    sectionId: section.id,
    sectionTitle: section.title,
    path: getArticlePath(section.id, article.slug),
  }))
)

export function findArticle(sectionId: string, articleSlug: string) {
  const section = docsSections.find((item) => item.id === sectionId)
  const article = section?.links.find((item) => item.slug === articleSlug)

  if (!section || !article) return null

  return {
    ...article,
    sectionId: section.id,
    sectionTitle: section.title,
    path: getArticlePath(section.id, article.slug),
  }
}
